#!/usr/bin/env python3
"""Draws Legato's icon: two beamed sixteenth notes on lumeo's dark tile.

    packaging/icon.py      writes icon.svg (48 px and up), icon-small.svg (32 px and
                           below: thicker stems, a wider gap between the beams),
                           icon-symbolic.svg (the notes alone, one color, for GNOME)
                           and legato.ico (Windows, rendered with rsvg-convert)

The notes are built the way a score is engraved, in staff spaces (sp). The notehead
is Bravura's noteheadBlack (Steinberg, SIL Open Font License 1.1); beam thickness and
spacing are Bravura's engraving defaults (SMuFL). Only the stem is thicker than in
print (0.17 sp instead of 0.12), so it survives at small sizes. Corners are softened
a little, as print is not quite sharp either.
"""
import math
import re
import struct
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent

# noteheadBlack (U+E0A4) in font units: 1000 per em, 250 per staff space, y down.
NOTEHEAD = "M97 125C186 125 295 43 295-42C295-93 255-125 198-125C88-125 0-44 0 42C0 94 43 125 97 125Z"
NOTEHEAD_WIDTH = 1.18  # sp; stems attach at its right edge (anchor stemUpSE)

INK = "#f4f4f6"


def notes(stem, gap, spacing=1.8, rise=0.6, stem_len=3.5, beam=0.5):
    """Outline of the two notes: (stems and beams with their corner radii, the gap
    between the beams, the noteheads' offsets, the bounding box), in sp, y down."""
    s1r, s2r = NOTEHEAD_WIDTH, spacing + NOTEHEAD_WIDTH
    s1l, s2l = s1r - stem, s2r - stem
    slope = -rise / (s2r - s1r)
    top = lambda x: -stem_len + (x - s1r) * slope
    depth = 2 * beam + gap
    out, inn = 0.12, 0.15
    # Clockwise from the foot of the first stem, which sits inside its notehead.
    body = [((s1l, -0.1), 0), ((s1l, top(s1l)), out), ((s2r, top(s2r)), out),
            ((s2r, -1.1), 0), ((s2l, -1.1), 0), ((s2l, top(s2l) + depth), inn),
            ((s1r, top(s1r) + depth), inn), ((s1r, -0.1), 0)]
    hole = [((s1r, top(s1r) + beam), .05), ((s2l, top(s2l) + beam), .05),
            ((s2l, top(s2l) + beam + gap), .05), ((s1r, top(s1r) + beam + gap), .05)]
    heads = [(0, 0), (spacing, -1)]
    return body, hole, heads, (0, top(s2r), s2r, 0.5)


def rounded(poly, scale, ox, oy):
    """A closed path through the points, each corner cut by a quadratic of its radius."""
    pts = [(x * scale + ox, y * scale + oy, r * scale) for (x, y), r in poly]
    f = lambda x, y: f"{x:.2f} {y:.2f}"
    d = []
    for i, (x, y, r) in enumerate(pts):
        px, py, _ = pts[i - 1]
        nx, ny, _ = pts[(i + 1) % len(pts)]
        if r <= 0:
            d.append(f"L{f(x, y)}")
            continue
        d1, d2 = math.hypot(px - x, py - y), math.hypot(nx - x, ny - y)
        r = min(r, d1 / 2, d2 / 2)
        a = (x + (px - x) / d1 * r, y + (py - y) / d1 * r)
        b = (x + (nx - x) / d2 * r, y + (ny - y) / d2 * r)
        d.append(f"L{f(*a)} Q{f(x, y)} {f(*b)}")
    return "M" + " ".join(d)[1:] + " Z"


def notehead(scale, ox, oy, hx, hy):
    out, pair = [], []
    for tok in re.findall(r"[A-Za-z]|-?\d+(?:\.\d+)?", NOTEHEAD):
        if tok.isalpha():
            out.append(tok)
            continue
        pair.append(float(tok))
        if len(pair) == 2:
            x = (pair[0] / 250 + hx) * scale + ox
            y = (pair[1] / 250 + hy) * scale + oy
            out.append(f"{x:.2f} {y:.2f}")
            pair = []
    return " ".join(out)


def glyph(stem, gap, size, height, fill):
    """The notes centered in a size x size box, `height` units tall."""
    body, hole, heads, (x0, y0, x1, y1) = notes(stem, gap)
    scale = height / (y1 - y0)
    ox = size / 2 - (x1 - x0) * scale / 2 - x0 * scale
    oy = size / 2 - height / 2 - y0 * scale
    paths = [f'<path d="{notehead(scale, ox, oy, hx, hy)}"/>' for hx, hy in heads]
    paths.append(f'<path fill-rule="evenodd" d="{rounded(body, scale, ox, oy)} {rounded(hole, scale, ox, oy)}"/>')
    return f'<g fill="{fill}">\n    ' + "\n    ".join(paths) + "\n  </g>"


def tile_icon(note, stem, gap):
    # Comments stay inside <svg>: gdk-pixbuf (GNOME Shell's app grid) looks for "<svg"
    # in the first bytes only.
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 128 128" width="128" height="128">
  <!-- Generated by packaging/icon.py ({note}). The noteheads are Bravura's
       (Steinberg, SIL Open Font License 1.1). -->
  <defs>
    <linearGradient id="ground" x1="0" y1="0" x2="0" y2="1">
      <stop offset="0" stop-color="#26262a"/>
      <stop offset="1" stop-color="#0a0a0b"/>
    </linearGradient>
  </defs>
  <rect x="4" y="4" width="120" height="120" rx="28" fill="url(#ground)"/>
  <rect x="4.5" y="4.5" width="119" height="119" rx="27.5" fill="none" stroke="#fff" stroke-opacity="0.08"/>
  {glyph(stem, gap, 128, 86, INK)}
</svg>
'''


def symbolic():
    return f'''<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 16 16" width="16" height="16">
  <!-- Generated by packaging/icon.py: the notes alone, one color, which GNOME recolors. -->
  {glyph(0.3, 0.45, 16, 14, "#222222")}
</svg>
'''


def ico():
    """A Windows icon of PNG images, each size rendered from the drawing made for it."""
    images = []
    for size in (16, 24, 32, 48, 64, 128, 256):
        src = HERE / ("icon-small.svg" if size <= 32 else "icon.svg")
        png = subprocess.run(["rsvg-convert", "-w", str(size), "-h", str(size), str(src)],
                             check=True, capture_output=True).stdout
        images.append((size, png))
    offset = 6 + 16 * len(images)
    head = struct.pack("<HHH", 0, 1, len(images))
    entries, data = b"", b""
    for size, png in images:
        side = size % 256  # 0 means 256
        entries += struct.pack("<BBBBHHII", side, side, 0, 0, 1, 32, len(png), offset + len(data))
        data += png
    (HERE / "legato.ico").write_bytes(head + entries + data)


def main():
    (HERE / "icon.svg").write_text(tile_icon("48 px and up", 0.17, 0.25))
    (HERE / "icon-small.svg").write_text(tile_icon("32 px and below: thicker stems, wider gap", 0.28, 0.42))
    (HERE / "icon-symbolic.svg").write_text(symbolic())
    ico()


if __name__ == "__main__":
    main()
